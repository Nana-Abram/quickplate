import { photos } from './photos.js';

const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

const item = (name, category, pricePesewas, description, photo, { isAvailable = true } = {}) => ({
  id: slugify(name),
  name,
  description,
  category,
  pricePesewas,
  isAvailable,
  imageUrl: photos[photo],
});

const restaurant = ({ name, photo, menu, ...fields }) => ({
  id: slugify(name),
  name,
  imageUrl: photos[photo],
  ...fields,
  menu: menu.map((menuItem, index) => ({ ...menuItem, sortOrder: index })),
});

