// Sample data for `npm run seed`. Prices are integer pesewas (GHS 1 = 100).

const image = (seed) => `https://picsum.photos/seed/${seed}/600/400`;

const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

const item = (name, category, pricePesewas, description, { isAvailable = true } = {}) => ({
  id: slugify(name),
  name,
  description,
  category,
  pricePesewas,
  isAvailable,
  imageUrl: image(`qp-${slugify(name)}`),
});

const restaurant = ({ name, menu, ...fields }) => ({
  id: slugify(name),
  name,
  imageUrl: image(`qp-${slugify(name)}`),
  ...fields,
  menu: menu.map((menuItem, index) => ({ ...menuItem, sortOrder: index })),
});

